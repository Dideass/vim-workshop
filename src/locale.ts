export function translate(language:Language, text:string, values:Record<string,string|number>={}):string {
  const plain=text.replace(/^Error: /,'');
  let result=language==='zh'?(chinese[plain]??plain):text;
  if(language==='zh'&&!chinese[plain]){
    const edition=plain.match(/^English text checked against eBook (\d+);/);
    if(edition)result=`英文文本据电子书 ${edition[1]} 核对；已统一标点并按练习需要重新分行。`;
  }
  for(const [key,value] of Object.entries(values))result=result.replaceAll(`{${key}}`,String(value));
  return result;
}

export function localizeLevel(level:LevelDefinition,language:Language,_variant=false):LevelDefinition {
 return language==='zh'&&level.zh?{...level,...level.zh}:level;
}
